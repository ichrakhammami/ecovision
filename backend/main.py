@app.put("/centres/{identifier}")
def save_centre(identifier: int, body: Centre,user=Depends(current)):
    allow(user,"centre","admin")
    data = body.model_dump()
    if not set(data["materials"].split(",")) <= CATEGORIES.keys():
        raise HTTPException(422,"Catégories de tri invalides.")
    if identifier == 0:
        return run("""INSERT INTO centres(name,address,lat,lng,materials,availability,owner_id)
            VALUES(:name,:address,:lat,:lng,:materials,:availability,:owner) RETURNING id""", **data,owner=user["id"])[0]
    rows=run("""UPDATE centres SET name=:name,address=:address,lat=:lat,lng=:lng,materials=:materials,availability=:availability
        WHERE id=:identifier AND (owner_id=:owner OR :admin=1) RETURNING id""", **data,identifier=identifier,owner=user["id"],admin=int(user["role"]=="admin"))
    if not rows:
        raise HTTPException(404,"Centre introuvable.")
    return rows[0]


