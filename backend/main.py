@app.post("/scan")
async def scan(image: UploadFile=File(...),user=Depends(current)):
    from backend.classifier import classify

    data=await image.read(5_000_001)
    if len(data)>5_000_000:
        raise HTTPException(413,"Image trop volumineuse.")
    try:
        with Image.open(BytesIO(data)) as source:
            result=classify(source.convert("RGB"))
    except (OSError,ValueError,Image.DecompressionBombError) as exc:
        raise HTTPException(422,"Image invalide.") from exc
    if result is None:
        return {"manual": True,"categories": CATEGORIES}
    category,confidence=result
    return {"category":category,"confidence":confidence,"advice":CATEGORIES[category]}

