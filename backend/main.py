@app.post("/deposits/{identifier}/confirm")
def confirm(identifier: int,user=Depends(current)):
    allow(user,"centre","admin")
    with engine.begin() as db:
        owner_query = "SELECT id FROM centres WHERE owner_id=:owner"
        row=db.execute(text(f"""UPDATE deposits SET status='Confirmé' WHERE id=:id AND status='En attente'
            AND (:admin=1 OR centre_id IN ({owner_query})) RETURNING user_id"""),
            {"id":identifier,"owner":user["id"],"admin":int(user["role"]=="admin")}).first()
        if not row:
            raise HTTPException(409,"Dépôt indisponible ou déjà confirmé.")
        db.execute(text("UPDATE users SET points=points+25 WHERE id=:id"),{"id":row.user_id})
    return {"points":25}


