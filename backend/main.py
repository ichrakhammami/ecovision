def run(sql, **params):
    with engine.begin() as db:
        result = db.execute(text(sql), params)
        return [dict(row) for row in result.mappings()] if result.returns_rows else []


def hash_password(password, salt):
    return hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()


def create_user(email, name, password, role="citoyen", points=0):
    salt = secrets.token_hex(16)
    return run("""INSERT INTO users(email,name,password,salt,role,points)
        VALUES(:email,:name,:password,:salt,:role,:points)
        ON CONFLICT(email) DO NOTHING RETURNING id""",
        email=email, name=name, password=hash_password(password, salt), salt=salt, role=role, points=points)


