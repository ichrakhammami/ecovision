@app.post("/rewards/{identifier}/redeem")
def redeem(identifier: int,user=Depends(current)):
    allow(user,"citoyen")
    with engine.begin() as db:
        reward=db.execute(text("SELECT cost FROM rewards WHERE id=:id"),{"id":identifier}).first()
        if not reward:
            raise HTTPException(404)
        points=db.execute(text("UPDATE users SET points=points-:cost WHERE id=:id AND points>=:cost RETURNING points"),
            {"id":user["id"],"cost":reward.cost}).scalar()
        if points is None:
            raise HTTPException(409,"Votre solde est insuffisant.")
        code=f"ECO-{secrets.token_hex(6).upper()}"
        db.execute(text("INSERT INTO redemptions(user_id,reward_id,code) VALUES(:uid,:rid,:code)"),
            {"uid":user["id"],"rid":identifier,"code":code})
    return {"code":code,"points":points}


