def current(auth: HTTPAuthorizationCredentials | None = Depends(bearer)):
    if auth:
        rows = run("""SELECT u.id,u.name,u.email,u.role,u.points FROM users u
            JOIN sessions s ON s.user_id=u.id WHERE s.token=:token AND s.expires>:now""",
            token=hashlib.sha256(auth.credentials.encode()).hexdigest(),now=int(time.time()))
        if rows:
            return rows[0]
    raise HTTPException(401, "Identifiez-vous pour continuer.")


def allow(user, *roles):
    if user["role"] not in roles:
        raise HTTPException(403, "Accès réservé.")


class Auth(BaseModel):
    email: str = Field(min_length=5, max_length=254, pattern=r"^[^\s@]+@[^\s@]+\.[^\s@]+$")
    password: str = Field(min_length=8, max_length=128)
    name: str | None = Field(default=None, min_length=2, max_length=80)


def login_user(email, password):
    rows = run("SELECT * FROM users WHERE email=:email", email=email)
    if not rows or not hmac.compare_digest(hash_password(password, rows[0]["salt"]), rows[0]["password"]):
        raise HTTPException(401,"Identifiants incorrects.")
    user = rows[0]
    token = secrets.token_urlsafe(32)
    run("INSERT INTO sessions(token,user_id,expires) VALUES(:token,:uid,:expires)",
        token=hashlib.sha256(token.encode()).hexdigest(),uid=user["id"],expires=int(time.time())+86400)
    return {"token":token,"user":{key:user[key] for key in ("id","name","role","points","email")}}


