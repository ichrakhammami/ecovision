@app.get("/centres")
def centres(lat: float = 36.8065, lng: float = 10.1815):
    rows = run("SELECT * FROM centres")
    for row in rows:
        a = math.sin(math.radians(row["lat"]-lat)/2)**2
        a += math.cos(math.radians(lat))*math.cos(math.radians(row["lat"]))*math.sin(math.radians(row["lng"]-lng)/2)**2
        row["km"] = round(12742*math.asin(math.sqrt(min(1,a))), 1)
    return sorted(rows,key=lambda row: row["km"])


class Centre(BaseModel):
    name: str = Field(min_length=2,max_length=120)
    address: str = Field(min_length=2,max_length=200)
    lat: float = Field(ge=-90,le=90)
